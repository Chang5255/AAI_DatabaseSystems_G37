-- 05_crud.sql : create / read / update / delete for users and ratings
--
-- Run AFTER 02_load.sql. Safe to re-run: it creates its own demo user,
-- works on that user only, and deletes the user at the end, so the
-- loaded data is unchanged afterwards.
--
-- Parameters are MySQL session variables (@uid, @movie_id, ...) so the
-- script runs as-is in Workbench. In the Python back end the same
-- statements are used with %s placeholders instead, e.g.
--   cur.execute("SELECT ... WHERE user_id = %s", (user_id,))
-- Never build SQL by string concatenation (SQL injection).
--
-- Rules enforced by the database, not the application:
--   rating range 0.5-5.0 and half-star steps  -> CHECK constraints
--   one rating per user per film              -> composite PRIMARY KEY
--   rating must point to a real user and film -> FOREIGN KEYs
--   deleting a user deletes their ratings     -> ON DELETE CASCADE
-- =====================================================================

USE moviedb;

-- Clean up a leftover demo user if a previous run was interrupted.
DELETE FROM users WHERE username = 'demo_user_g37';


-- =====================================================================
-- USERS
-- =====================================================================

-- C1. Create a user. user_id is generated by AUTO_INCREMENT.
INSERT INTO users (username, display_name)
VALUES ('demo_user_g37', 'Demo User');

SET @uid = LAST_INSERT_ID();
SELECT @uid AS new_user_id;

-- R1. Read one user.
SELECT user_id, username, display_name, created_at
  FROM users
 WHERE user_id = @uid;

-- R2. List all users with how many ratings each has given
--     (user selection screen in the app).
SELECT user_id, username, display_name, ratings_given
  FROM v_user_activity
 ORDER BY username;

-- U1. Update a user's display name.
UPDATE users
   SET display_name = 'Demo User (edited)'
 WHERE user_id = @uid;

SELECT user_id, username, display_name FROM users WHERE user_id = @uid;


-- =====================================================================
-- RATINGS
-- =====================================================================

-- C2. Create ratings (Avatar, The Dark Knight, Inception).
INSERT INTO ratings (user_id, movie_id, rating_value)
VALUES (@uid, 19995, 4.5),
       (@uid,   155, 5.0),
       (@uid, 27205, 4.0);

-- C3. "Rate this film" button: insert, or overwrite if already rated.
--     ON DUPLICATE KEY UPDATE uses the composite primary key
--     (user_id, movie_id), so a second rating replaces the first
--     instead of failing or creating a duplicate.
--     'AS new' is the MySQL 8.0.19+ row-alias syntax.
SET @movie_id = 603;   -- The Matrix
SET @rating   = 3.5;
INSERT INTO ratings (user_id, movie_id, rating_value)
VALUES (@uid, @movie_id, @rating) AS new
ON DUPLICATE KEY UPDATE rating_value = new.rating_value;

SET @rating = 4.5;     -- same user, same film: updates, no duplicate
INSERT INTO ratings (user_id, movie_id, rating_value)
VALUES (@uid, @movie_id, @rating) AS new
ON DUPLICATE KEY UPDATE rating_value = new.rating_value;

-- R3. Read one user's ratings with film titles ("My ratings" page).
SELECT r.movie_id, m.title, YEAR(m.release_date) AS release_year,
       r.rating_value, r.rated_at, r.updated_at
  FROM ratings r
  JOIN movies m ON m.movie_id = r.movie_id
 WHERE r.user_id = @uid
 ORDER BY r.rated_at DESC, m.title;

-- R4. Read one film's rating summary (movie detail page).
SET @movie_id = 19995;
SELECT m.movie_id, m.title,
       COUNT(r.user_id)               AS user_rating_count,
       ROUND(AVG(r.rating_value), 2)  AS user_avg_rating,
       MIN(r.rating_value)            AS lowest,
       MAX(r.rating_value)            AS highest
  FROM movies m
  LEFT JOIN ratings r ON r.movie_id = m.movie_id
 WHERE m.movie_id = @movie_id
 GROUP BY m.movie_id, m.title;

-- R5. Star distribution for one film (histogram on the detail page).
SELECT rating_value, COUNT(*) AS votes
  FROM ratings
 WHERE movie_id = @movie_id
 GROUP BY rating_value
 ORDER BY rating_value DESC;

-- U2. Update a rating. updated_at is set automatically by
--     ON UPDATE CURRENT_TIMESTAMP in the table definition.
UPDATE ratings
   SET rating_value = 3.5
 WHERE user_id = @uid
   AND movie_id = 19995;

SELECT movie_id, rating_value, rated_at, updated_at
  FROM ratings
 WHERE user_id = @uid AND movie_id = 19995;

-- D1. Delete one rating.
DELETE FROM ratings
 WHERE user_id = @uid
   AND movie_id = 27205;

SELECT COUNT(*) AS ratings_left_for_demo_user
  FROM ratings WHERE user_id = @uid;     -- expect 3


-- =====================================================================
-- DELETE USER (cascades to ratings)
-- =====================================================================

-- D2. Deleting the user removes all of their ratings through
--     fk_ratings_user ON DELETE CASCADE. No separate DELETE is needed.
--     Note for the back end: MongoDB has no foreign keys, so this user's
--     user_tags and user_activity_logs must be deleted there explicitly.
SELECT COUNT(*) AS ratings_before_user_delete
  FROM ratings WHERE user_id = @uid;     -- expect 3

DELETE FROM users WHERE user_id = @uid;

SELECT
  (SELECT COUNT(*) FROM users   WHERE user_id = @uid) AS user_rows_after,
  (SELECT COUNT(*) FROM ratings WHERE user_id = @uid) AS rating_rows_after;
                                         -- expect 0 and 0

-- Final check: loaded data is back to its original size.
SELECT (SELECT COUNT(*) FROM users)   AS users_total,    -- expect 12
       (SELECT COUNT(*) FROM ratings) AS ratings_total;  -- expect 784
